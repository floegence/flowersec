import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const wasm = await readFile(fileURLToPath(import.meta.resolve('brotli-dec-wasm/web/bg.wasm')));
const inventory = JSON.parse(await readFile(path.join(root, '../scripts/brotli-wasm-components.json'), 'utf8'));
if (createHash('sha256').update(wasm).digest('hex') !== inventory.wasm_sha256) throw new Error('Brotli WASM source inventory drift');
const id = path.join(root, 'virtual-flowersec-brotli.js');
const result = await build({
  configFile: false,
  root,
  logLevel: 'error',
  plugins: [{
    name: 'flowersec-brotli-worker',
    resolveId(value) { if (value === id) return '\0' + id; },
    load(value) {
      if (value !== '\0' + id) return;
      return `import { initSync, BrotliDecStream } from 'brotli-dec-wasm/web';\ninitSync({module:Uint8Array.from(atob(${JSON.stringify(wasm.toString('base64'))}), c => c.charCodeAt(0))});\nexport { BrotliDecStream };`;
    },
  }],
  build: {
    write: false,
    minify: true,
    target: 'es2022',
    lib: { entry: id, name: 'FlowersecBrotli', formats: ['iife'] },
  },
});
const output = (Array.isArray(result) ? result[0] : result).output;
if (output.length !== 1 || output[0].type !== 'chunk') throw new Error('Brotli worker must be self-contained');
const source = `function createBrotliDecoder() { ${output[0].code}\nreturn new FlowersecBrotli.BrotliDecStream(); }`;
const target = path.join(root, 'src/generated/brotliWorker.ts');
const generated = '// Generated by scripts/generate-brotli-worker.mjs; DO NOT EDIT.\n' +
  '// Contains brotli-dec-wasm; see THIRD_PARTY_NOTICES.md.\n' +
  `export const brotliWorkerSource = ${JSON.stringify(source)};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) throw new Error('Brotli worker source drift');
} else {
  await writeFile(target, generated);
}
